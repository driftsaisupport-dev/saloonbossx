#!/usr/bin/env node
/**
 * Embed google-apps-script/BranchSync.gs into the app so the owner can share
 * the exact script to their laptop from Settings → Branches & Cloud.
 * Run after editing the .gs file:  node tools/embed-script.js
 * (preflight runs it automatically).
 */
const fs = require('fs');
const path = require('path');
const src = fs.readFileSync(path.join(__dirname, '..', 'google-apps-script', 'BranchSync.gs'), 'utf8');
const out = `// AUTO-GENERATED by tools/embed-script.js from google-apps-script/BranchSync.gs — do not edit.\nexport const BRANCH_SYNC_SCRIPT = ${JSON.stringify(src)};\n`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'services', 'sync', 'scriptSource.ts'), out);
console.log('Embedded BranchSync.gs (' + src.length + ' chars)');
