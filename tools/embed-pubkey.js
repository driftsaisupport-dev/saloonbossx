#!/usr/bin/env node
/**
 * Bakes license-public.key into src/services/licensePubKey.ts, so every build —
 * Expo Go, EAS, a laptop with an old .env — always trusts YOUR signing key.
 * Runs from keygen and preflight. Safe to run any time.
 */
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const keys = [];
try { keys.push(fs.readFileSync(path.join(root, 'license-public.key'), 'utf8').trim()); } catch {}
const extraFile = path.join(root, 'license-public.extra.keys');   // optional: older keys, one per line
try { for (const l of fs.readFileSync(extraFile, 'utf8').split('\n')) if (l.trim() && !l.startsWith('#')) keys.push(l.trim()); } catch {}
const valid = [...new Set(keys)].filter(k => Buffer.from(k.replace(/-/g, '+').replace(/_/g, '/'), 'base64').length === 32);
const out = path.join(root, 'src', 'services', 'licensePubKey.ts');
fs.writeFileSync(out, `// GENERATED by tools/embed-pubkey.js from license-public.key — do not edit by hand.
// Public keys are not secret. The app accepts a key signed by ANY of these.
export const EMBEDDED_LICENSE_PUBKEYS: string[] = ${JSON.stringify(valid, null, 2)};
`);
console.log(`Embedded ${valid.length} licence public key(s) into src/services/licensePubKey.ts`);
